<?php

declare(strict_types=1);

namespace ModernORM\Bundle\Tests;

use ModernORM\Bundle\ConnectionFactory;
use ModernORM\Bundle\ReverseEngineering\ImportCommand;
use ModernORM\Configuration;
use ModernORM\EntityManager;
use ModernORM\Mapping\Driver\AttributeDriver;
use ModernORM\Statistics;
use ModernORM\Tools\SchemaTool;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Console\Tester\CommandTester;

final class ReverseEngineeringIntegrationTest extends TestCase
{
    public function testImportPreviewPersistenceRoundTripAndOverwriteProtection(): void
    {
        $url = getenv('MODERNORM_TEST_URL');
        if (!$url) {
            self::markTestSkipped('Set MODERNORM_TEST_URL for PostgreSQL integration.');
        }
        $connection = ConnectionFactory::create($url, '17', new Statistics(false));
        $suffix = bin2hex(random_bytes(6));
        $schema = 'modernorm_import_'.$suffix;
        $directory = sys_get_temp_dir().'/'.$schema;
        $namespace = 'ImportTest'.$suffix;
        $connection->executeStatement('CREATE SCHEMA '.$schema);
        try {
            $connection->executeStatement('CREATE TABLE '.$schema.'.users (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(120) NOT NULL, CONSTRAINT users_name_key UNIQUE (name))');
            $connection->executeStatement('CREATE TABLE '.$schema.'.orders (id serial PRIMARY KEY, user_id integer REFERENCES '.$schema.'.users(id) ON DELETE SET NULL, total numeric(12,2) NOT NULL)');
            $connection->executeStatement('CREATE INDEX orders_user_idx ON '.$schema.'.orders(user_id)');
            $connection->executeStatement('CREATE TABLE '.$schema.'.unsupported (a integer, b integer, PRIMARY KEY(a,b))');
            $connection->executeStatement('CREATE TABLE '.$schema.'.computed (id integer PRIMARY KEY, value integer GENERATED ALWAYS AS (id + 1) STORED)');
            $tester = new CommandTester(new ImportCommand($connection, sys_get_temp_dir()));
            $options = ['--schema' => $schema, '--namespace' => $namespace, '--output' => $directory];
            self::assertSame(0, $tester->execute($options + ['--dry-run' => true]));
            self::assertDirectoryDoesNotExist($directory);
            self::assertStringContainsString('requires one scalar primary key', $tester->getDisplay());
            self::assertStringContainsString('generated columns require manual mapping', $tester->getDisplay());
            self::assertSame(0, $tester->execute($options + ['--dry-run' => true, '--table' => ['orders']]));
            self::assertStringNotContainsString('class Users', $tester->getDisplay());
            self::assertMatchesRegularExpression('/requires manual association\s+mapping/', $tester->getDisplay());
            try {
                $tester->execute($options + ['--table' => ['absent']]);
                self::fail('Unknown table must fail.');
            } catch (\InvalidArgumentException $error) {
                self::assertStringContainsString('Unknown table', $error->getMessage());
            }
            self::assertSame(0, $tester->execute($options));
            self::assertFileExists($directory.'/Users.php');
            self::assertFileExists($directory.'/Orders.php');
            require $directory.'/Users.php';
            require $directory.'/Orders.php';
            $configuration = new Configuration();
            $configuration->setMetadataDriverImpl(new AttributeDriver([$directory]));
            $manager = new EntityManager($connection, $configuration);
            $usersClass = $namespace.'\\Users';
            $ordersClass = $namespace.'\\Orders';
            $metadata = [$manager->getClassMetadata($usersClass), $manager->getClassMetadata($ordersClass)];
            $connection->executeStatement('DROP TABLE '.$schema.'.computed');
            $connection->executeStatement('DROP TABLE '.$schema.'.unsupported');
            self::assertSame([], (new SchemaTool($manager))->getUpdateSchemaSql($metadata));
            $user = new $usersClass();
            $user->name = 'Reverse engineering';
            $order = new $ordersClass();
            $order->user = $user;
            $order->total = '123.45';
            $manager->persist($user);
            $manager->persist($order);
            $manager->flush();
            $id = $order->id;
            $manager->clear();
            $loaded = $manager->find($ordersClass, $id);
            self::assertSame('123.45', $loaded->total);
            self::assertSame('Reverse engineering', $loaded->user->name);
            $before = file_get_contents($directory.'/Users.php');
            try {
                $tester->execute($options);
                self::fail('Existing entities must not be overwritten.');
            } catch (\RuntimeException $error) {
                self::assertStringContainsString('Refusing to overwrite', $error->getMessage());
            }
            self::assertSame($before, file_get_contents($directory.'/Users.php'));
        } finally {
            $connection->executeStatement('DROP SCHEMA '.$schema.' CASCADE');
            foreach (glob($directory.'/*.php') ?: [] as $file) {
                unlink($file);
            }
            if (is_dir($directory)) {
                rmdir($directory);
            }
            $connection->close();
        }
    }
}
