<?php

declare(strict_types=1);

namespace ModernORM\Bundle\Tests;

use Doctrine\DBAL\DriverManager;
use Doctrine\DBAL\Tools\DsnParser;
use Doctrine\Persistence\Mapping\Driver\ClassLocator;
use ModernORM\Bundle\DataTransfer\TransferCommand;
use ModernORM\Configuration;
use ModernORM\Mapping as ORM;
use ModernORM\Mapping\Driver\AttributeDriver;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Console\Tester\CommandTester;

final class ExecuteIntegrationTest extends TestCase
{
    public function testFinalTransferToConfiguredApplicationDatabase(): void
    {
        $mysqlUrl = getenv('MODERNORM_TEST_MYSQL_URL');
        $pgUrl = getenv('MODERNORM_TEST_URL');
        if (!$mysqlUrl || !$pgUrl) {
            self::markTestSkipped('Set both database test URLs; PostgreSQL role needs CREATEDB.');
        }
        $parser = new DsnParser(['mysql' => 'pdo_mysql', 'postgresql' => 'pdo_pgsql']);
        $source = DriverManager::getConnection($parser->parse($mysqlUrl));
        $admin = DriverManager::getConnection($parser->parse($pgUrl));
        $suffix = bin2hex(random_bytes(5));
        $sourceName = 'modernorm_execute_source_'.$suffix;
        $targetName = 'modernorm_execute_'.$suffix;
        $sourceCreated = $targetCreated = false;
        $target = null;
        $rulesPath = sys_get_temp_dir().'/modernorm_execute_'.$suffix.'.json';
        $logPath = $rulesPath.'.jsonl';
        try {
            $source->executeStatement('CREATE DATABASE '.$sourceName);
            $sourceCreated = true;
            $source->executeStatement('USE '.$sourceName);
            $admin->executeStatement('CREATE DATABASE '.$targetName);
            $targetCreated = true;
            $params = $parser->parse($pgUrl);
            $params['dbname'] = $targetName;
            $target = DriverManager::getConnection($params);
            $source->executeStatement('CREATE TABLE clients (id BIGINT UNSIGNED PRIMARY KEY, name VARCHAR(100) NULL)');
            $source->executeStatement('CREATE TABLE entries (id INT PRIMARY KEY, client_id BIGINT UNSIGNED NOT NULL, amount DECIMAL(12,2) NOT NULL)');
            $source->executeStatement("INSERT INTO clients VALUES(41,' Alice '),(50,'Bob')");
            $source->executeStatement('INSERT INTO entries VALUES(7,41,12.34)');
            $target->executeStatement('CREATE TABLE clients (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL)');
            $target->executeStatement('CREATE UNIQUE INDEX clients_name_unique ON clients(lower(name))');
            $target->executeStatement('CREATE TABLE entries (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client_id BIGINT REFERENCES clients(id) DEFERRABLE INITIALLY DEFERRED, amount NUMERIC(12,2) NOT NULL CHECK(amount>=0))');
            $target->executeStatement('CREATE TABLE auditlog(name TEXT)');
            $target->executeStatement("CREATE FUNCTION audit_client() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN INSERT INTO auditlog VALUES(NEW.name); RETURN NEW; END'");
            $target->executeStatement('CREATE TRIGGER audit_client AFTER INSERT ON clients FOR EACH ROW EXECUTE FUNCTION audit_client()');
            $_SERVER['MODERNORM_EXECUTE_SOURCE'] = preg_replace('~/[^/]*(\?.*)?$~', '/'.$sourceName, $mysqlUrl);
            $_SERVER['MODERNORM_EXECUTE_TARGET'] = preg_replace('~/[^/]*(\?.*)?$~', '/'.$targetName, $pgUrl);
            $configuration = new Configuration();
            $configuration->setMetadataDriverImpl(new AttributeDriver(new class () implements ClassLocator {
                public function getClassNames(): array
                {
                    return [ExecuteClient::class, ExecuteEntry::class];
                }
            }));
            file_put_contents($rulesPath, json_encode(['version' => 1, 'rules' => [['id' => 'trim_client', 'table' => 'clients', 'column' => 'name', 'operation' => 'trim']]], JSON_THROW_ON_ERROR));
            // The configured application connection and explicit target are the same DB.
            $tester = new CommandTester(new TransferCommand($configuration, $target));
            $options = ['--source-url-env' => 'MODERNORM_EXECUTE_SOURCE', '--target-url-env' => 'MODERNORM_EXECUTE_TARGET', '--rules' => $rulesPath, '--batch-size' => '1', '--execute' => true, '--format' => 'json'];
            self::assertSame(0, $tester->execute($options + ['--change-log' => $logPath], ['interactive' => false, 'capture_stderr_separately' => true]));
            $result = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame('execute', $result['mode']);
            self::assertStringContainsString('Stop writes to MySQL', $tester->getErrorOutput());
            self::assertStringNotContainsString('[WARNING]', $tester->getDisplay());
            self::assertSame($targetName, $result['connections']['target_database']);
            self::assertArrayNotHasKey('rehearsal', $result);
            self::assertSame('committed', $result['transfer']['status']);
            self::assertTrue($result['transfer']['target_data_committed']);
            self::assertTrue($result['data_scanned']);
            self::assertTrue($result['transfer']['constraints_checked']);
            self::assertSame(3, $result['transfer']['rows_loaded']);
            self::assertTrue($result['transfer']['tables']['clients']['keys_verified']);
            self::assertSame(1, $result['transfer']['transformations']['changed_values']);
            self::assertSame('Alice', $target->fetchOne('SELECT name FROM clients WHERE id=41'));
            self::assertSame(' Alice ', $source->fetchOne('SELECT name FROM clients WHERE id=41'));
            self::assertSame(2, (int) $target->fetchOne('SELECT count(*) FROM auditlog'));
            self::assertSame(51, (int) $target->fetchOne("SELECT nextval('clients_id_seq')"));
            self::assertSame(8, (int) $target->fetchOne("SELECT nextval('entries_id_seq')"));
            self::assertStringContainsString('"outcome":"committed"', file_get_contents($logPath));
            self::assertSame(1, $tester->execute($options, ['capture_stderr_separately' => true]));
            $result = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame('skipped_structural_errors', $result['transfer']['status']);
            self::assertSame(2, (int) $target->fetchOne('SELECT count(*) FROM clients'));
            $target->executeStatement('TRUNCATE clients,entries,auditlog RESTART IDENTITY CASCADE');
            $source->executeStatement('UPDATE clients SET name=NULL WHERE id=50');
            self::assertSame(1, $tester->execute($options, ['capture_stderr_separately' => true]));
            $result = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame('validation_failed', $result['transfer']['status']);
            self::assertSame(0, (int) $target->fetchOne('SELECT count(*) FROM clients'));
            $source->executeStatement("UPDATE clients SET name='Bob' WHERE id=50");
            $source->executeStatement('UPDATE entries SET amount=-1');
            self::assertSame(1, $tester->execute($options, ['capture_stderr_separately' => true]));
            $result = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame('23514', $result['transfer']['sqlstate']);
            self::assertFalse($result['transfer']['target_data_committed']);
            self::assertSame(0, (int) $target->fetchOne('SELECT count(*) FROM clients'));
            self::assertSame(0, (int) $target->fetchOne('SELECT count(*) FROM auditlog'));
            $source->executeStatement('UPDATE entries SET amount=12.34, client_id=999');
            self::assertSame(1, $tester->execute($options, ['capture_stderr_separately' => true]));
            $result = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame('23503', $result['transfer']['sqlstate']);
            self::assertSame('constraints', $result['transfer']['stage']);
            self::assertSame(0, (int) $target->fetchOne('SELECT count(*) FROM entries'));
            $source->executeStatement('UPDATE entries SET client_id=41');
            $source->executeStatement("UPDATE clients SET name='alice' WHERE id=50");
            self::assertSame(1, $tester->execute($options, ['capture_stderr_separately' => true]));
            $result = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame('23505', $result['transfer']['sqlstate']);
            self::assertSame(0, (int) $target->fetchOne('SELECT count(*) FROM clients'));
            self::assertSame(2, (int) $source->fetchOne('SELECT count(*) FROM clients'));
        } finally {
            unset($_SERVER['MODERNORM_EXECUTE_SOURCE'], $_SERVER['MODERNORM_EXECUTE_TARGET']);
            $target?->close();
            if ($sourceCreated) {
                $source->executeStatement('DROP DATABASE '.$sourceName);
            }
            if ($targetCreated) {
                $admin->executeStatement('DROP DATABASE '.$targetName);
            }
            $source->close();
            $admin->close();
            foreach ([$rulesPath, $logPath] as $path) {
                if (is_file($path)) {
                    unlink($path);
                }
            }
        }
    }
}

#[ORM\Entity, ORM\Table(name: 'clients')]
class ExecuteClient
{
    #[ORM\Id, ORM\Column(type: 'bigint'), ORM\GeneratedValue]
    public ?int $id = null;
    #[ORM\Column(length: 100)]
    public string $name;
}

#[ORM\Entity, ORM\Table(name: 'entries')]
class ExecuteEntry
{
    #[ORM\Id, ORM\Column(type: 'integer'), ORM\GeneratedValue]
    public ?int $id = null;
    #[ORM\ManyToOne(targetEntity: ExecuteClient::class), ORM\JoinColumn(name: 'client_id', nullable: false)]
    public ExecuteClient $client;
    #[ORM\Column(type: 'decimal', precision: 12, scale: 2)]
    public string $amount;
}
