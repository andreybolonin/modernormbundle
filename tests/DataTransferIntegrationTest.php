<?php

declare(strict_types=1);

namespace ModernORM\Bundle\Tests;

use Doctrine\DBAL\DriverManager;
use Doctrine\DBAL\Tools\DsnParser;
use Doctrine\Persistence\Mapping\ClassMetadata as PersistenceMetadata;
use Doctrine\Persistence\Mapping\Driver\ClassLocator;
use ModernORM\Bundle\DataTransfer\TransferCommand;
use ModernORM\Configuration;
use ModernORM\Mapping as ORM;
use ModernORM\Mapping\Driver\AttributeDriver;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Console\Tester\CommandTester;

final class DataTransferIntegrationTest extends TestCase
{
    public function testReadOnlyPlanAndBlockersAgainstRealDatabases(): void
    {
        $mysqlUrl = getenv('MODERNORM_TEST_MYSQL_URL');
        $postgresUrl = getenv('MODERNORM_TEST_URL');
        if (!$mysqlUrl || !$postgresUrl) {
            self::markTestSkipped('Set MODERNORM_TEST_MYSQL_URL and MODERNORM_TEST_URL.');
        }
        $parser = new DsnParser(['mysql' => 'pdo_mysql', 'postgresql' => 'pdo_pgsql']);
        $mysql = DriverManager::getConnection($parser->parse($mysqlUrl));
        $postgres = DriverManager::getConnection($parser->parse($postgresUrl));
        $suffix = bin2hex(random_bytes(5));
        $database = 'modernorm_transfer_'.$suffix;
        $schema = $database;
        $created = false;
        $pgCreated = false;
        try {
            $mysql->executeStatement('CREATE DATABASE '.$database);
            $created = true;
            $mysql->executeStatement('USE '.$database);
            $postgres->executeStatement('CREATE SCHEMA '.$schema);
            $pgCreated = true;
            $mysql->executeStatement('CREATE TABLE people (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL)');
            $mysql->executeStatement('CREATE TABLE purchases (id INT AUTO_INCREMENT PRIMARY KEY, person_id BIGINT UNSIGNED NOT NULL, amount DECIMAL(12,2) NOT NULL, FOREIGN KEY(person_id) REFERENCES people(id))');
            $mysql->executeStatement("INSERT INTO people(name) VALUES ('Source row')");
            $mysql->executeStatement('INSERT INTO purchases(person_id,amount) VALUES (1,12.34)');
            $postgres->executeStatement('CREATE TABLE '.$schema.'.people (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL)');
            $postgres->executeStatement('CREATE TABLE '.$schema.'.purchases (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, person_id BIGINT NOT NULL REFERENCES '.$schema.'.people(id), amount DECIMAL(12,2) NOT NULL)');
            $_SERVER['MODERNORM_TRANSFER_TEST_SOURCE'] = preg_replace('~/[^/]*(\?.*)?$~', '/'.$database, $mysqlUrl);
            $_SERVER['MODERNORM_TRANSFER_TEST_TARGET'] = $postgresUrl;
            $configuration = new Configuration();
            $configuration->setMetadataDriverImpl(new class ($schema) extends AttributeDriver {
                public function __construct(private readonly string $schema)
                {
                    parent::__construct(new class () implements ClassLocator {
                        public function getClassNames(): array
                        {
                            return [TransferPerson::class, TransferPurchase::class, TransferIgnoredSuperclass::class];
                        }
                    });
                }
                public function loadMetadataForClass(string $className, PersistenceMetadata $metadata): void
                {
                    parent::loadMetadataForClass($className, $metadata);
                    $metadata->setPrimaryTable(['name' => $metadata->getTableName(), 'schema' => $this->schema]);
                }
            });
            $tester = new CommandTester(new TransferCommand($configuration));
            $options = ['--source-url-env' => 'MODERNORM_TRANSFER_TEST_SOURCE', '--target-url-env' => 'MODERNORM_TRANSFER_TEST_TARGET', '--batch-size' => '1000', '--dry-run' => true, '--format' => 'json'];
            self::assertSame(0, $tester->execute($options));
            $plan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertFalse($plan['data_scanned']);
            self::assertSame([], $plan['errors']);
            self::assertSame(['people', 'purchases'], $plan['order']);
            self::assertSame(1000, $plan['tables']['people']['batch_size']);
            self::assertNotNull($plan['tables']['people']['sequence_after_load']);
            self::assertNotEmpty($plan['warnings']);
            self::assertSame(0, (int) $postgres->fetchOne('SELECT count(*) FROM '.$schema.'.people'));
            self::assertSame(1, (int) $mysql->fetchOne('SELECT count(*) FROM people'));
            self::assertSame(0, $tester->execute(array_replace($options, ['--batch-size' => '100000'])));
            $largeBatch = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame(32767, $largeBatch['tables']['people']['batch_size']);
            self::assertFalse((bool) $postgres->fetchOne('SELECT is_called FROM '.$schema.'.people_id_seq'));
            self::assertSame(0, $tester->execute(array_replace($options, ['--validate-data' => true, '--batch-size' => '1'])));
            $scan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertTrue($scan['data_scanned']);
            self::assertSame(2, $scan['validation']['rows_scanned']);
            self::assertSame(0, $scan['validation']['error_count']);
            self::assertFalse($scan['validation']['constraints_checked']);
            $mysql->executeStatement('ALTER TABLE people MODIFY name VARCHAR(200) NULL');
            $mysql->executeStatement("INSERT INTO people(id,name) VALUES (18446744073709551614,'high1'),(18446744073709551615,'high2'),(2,NULL)");
            $mysql->executeStatement('INSERT INTO people(id,name) VALUES (3,?)', [str_repeat('Ж', 101)]);
            $scanOptions = array_replace($options, ['--validate-data' => true, '--batch-size' => '1', '--max-error-examples' => '1']);
            self::assertSame(1, $tester->execute($scanOptions));
            $scan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertTrue($scan['data_scanned']);
            self::assertSame('complete', $scan['validation']['status']);
            self::assertSame(6, $scan['validation']['rows_scanned']);
            self::assertSame(4, $scan['validation']['error_count']);
            self::assertSame(4, $scan['validation']['invalid_rows']);
            self::assertCount(1, $scan['validation']['error_examples']);
            self::assertTrue($scan['validation']['examples_truncated']);
            self::assertSame(['id' => '2'], $scan['validation']['error_examples'][0]['primary_key']);
            self::assertSame('name', $scan['validation']['error_examples'][0]['column']);
            self::assertSame(0, (int) $postgres->fetchOne('SELECT count(*) FROM '.$schema.'.people'));
            self::assertFalse((bool) $postgres->fetchOne('SELECT is_called FROM '.$schema.'.people_id_seq'));
            self::assertSame(1, $tester->execute(array_replace($scanOptions, ['--max-error-examples' => '0'])));
            $scan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertSame([], $scan['validation']['error_examples']);
            self::assertSame(4, $scan['validation']['error_count']);
            $postgres->executeStatement("INSERT INTO ".$schema.".people(name) VALUES ('Existing target row')");
            $mysql->executeStatement('CREATE TABLE unmapped (a INT, b INT, PRIMARY KEY(a,b))');
            self::assertSame(1, $tester->execute($options));
            $plan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            $errors = implode(' ', $plan['errors']);
            self::assertStringContainsString('target table is not empty', $errors);
            self::assertStringContainsString('source table has no entity mapping', $errors);
            self::assertSame(1, $tester->execute(array_replace($options, ['--validate-data' => true])));
            $skipped = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertFalse($skipped['data_scanned']);
            self::assertSame('skipped_structural_errors', $skipped['validation']['status']);
            self::assertSame(0, $skipped['validation']['rows_scanned']);
            self::assertSame(1, (int) $postgres->fetchOne('SELECT count(*) FROM '.$schema.'.people'));
            $postgres->executeStatement('ALTER TABLE '.$schema.'.people ADD COLUMN last_purchase_id INT REFERENCES '.$schema.'.purchases(id)');
            self::assertSame(1, $tester->execute($options));
            $plan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertStringContainsString('Cyclic or unresolved', implode(' ', $plan['errors']));
            $mysql->executeStatement('ALTER TABLE people ADD COLUMN legacy_only VARCHAR(100)');
            $postgres->executeStatement('ALTER TABLE '.$schema.'.purchases ADD COLUMN required_extra TEXT NOT NULL');
            $postgres->executeStatement('ALTER TABLE '.$schema.'.purchases ALTER COLUMN amount TYPE TEXT USING amount::text');
            self::assertSame(1, $tester->execute($options));
            $plan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            $errors = implode(' ', $plan['errors']);
            self::assertStringContainsString('source column has no mapping', $errors);
            self::assertStringContainsString('required target column', $errors);
            self::assertStringContainsString('Unsupported conversion decimal -> text', $errors);
            $postgres->executeStatement('DROP TABLE '.$schema.'.purchases CASCADE');
            self::assertSame(1, $tester->execute($options));
            $plan = json_decode($tester->getDisplay(), true, flags: JSON_THROW_ON_ERROR);
            self::assertStringContainsString('does not exist', implode(' ', $plan['errors']));
            self::assertSame('Source row', $mysql->fetchOne('SELECT name FROM people WHERE id = 1'));
            self::assertSame('Existing target row', $postgres->fetchOne('SELECT name FROM '.$schema.'.people'));
        } finally {
            unset($_SERVER['MODERNORM_TRANSFER_TEST_SOURCE'], $_SERVER['MODERNORM_TRANSFER_TEST_TARGET']);
            if ($created) {
                $mysql->executeStatement('DROP DATABASE '.$database);
            }
            if ($pgCreated) {
                $postgres->executeStatement('DROP SCHEMA '.$schema.' CASCADE');
            }
            $mysql->close();
            $postgres->close();
        }
    }
}

#[ORM\Entity, ORM\Table(name: 'people')]
class TransferPerson
{
    #[ORM\Id, ORM\Column(type: 'bigint'), ORM\GeneratedValue]
    public ?int $id = null;
    #[ORM\Column(length: 100)]
    public string $name;
}

#[ORM\Entity, ORM\Table(name: 'purchases')]
class TransferPurchase
{
    #[ORM\Id, ORM\Column(type: 'integer'), ORM\GeneratedValue]
    public ?int $id = null;
    #[ORM\ManyToOne(targetEntity: TransferPerson::class), ORM\JoinColumn(name: 'person_id', nullable: false)]
    public TransferPerson $person;
    #[ORM\Column(type: 'decimal', precision: 12, scale: 2)]
    public string $amount;
}

#[ORM\MappedSuperclass]
abstract class TransferIgnoredSuperclass
{
    #[ORM\Column]
    public string $ignored;
}
